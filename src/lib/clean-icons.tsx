const createIcon = (name: string, symbol?: string): React.FC<any> => {
  // Normalize clean name without index_ prefix
  const cleanName = name.replace(/^index_/, '');
  const svgContent = SVG_ICONS[cleanName] || (symbol ? undefined : SVG_ICONS[name]);

  const Comp: React.FC<any> = ({
    size = 20,
    color,
    className = '',
    style = {},
    strokeWidth = 2,
    ...props
  }) => {
    if (svgContent) {
      return (
        <svg
          xmlns="http://www.w3.org/2000/svg"
          width={size}
          height={size}
          viewBox="0 0 24 24"
          fill="none"
          stroke={color || "currentColor"}
          strokeWidth={strokeWidth}
          strokeLinecap="round"
          strokeLinejoin="round"
          className={`inline-block shrink-0 select-none ${className}`}
          style={{ verticalAlign: 'middle', ...style }}
          {...props}
        >
          {svgContent}
        </svg>
      );
    }

    if (symbol || SYMBOLS[cleanName]) {
      const sym = symbol || SYMBOLS[cleanName];
      return (
        <span
          className={`inline-block leading-none select-none font-bold ${className}`}
          style={{
            fontSize: size ? Math.max(10, Number(size) - 2) : '0.9em',
            color: color || undefined,
            verticalAlign: 'middle',
            ...style
          }}
          {...props}
        >
          {sym}
        </span>
      );
    }

    return null;
  };

  Comp.displayName = name;
  return Comp;
};

