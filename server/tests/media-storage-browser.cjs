const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
module.exports = async ({ base, uploadPath }) => {
  const { default: puppeteer } = await import('puppeteer-core');
  const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const out = path.resolve('../work/media-storage-qa'); fs.mkdirSync(out, { recursive: true });
  const page = await browser.newPage(); page.setDefaultTimeout(20000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const click = async (label, scope = '') => {
    const handle = await page.waitForFunction(({ label, scope }) => [...document.querySelectorAll(scope + ' button')].find(el => el.textContent.trim() === label && el.getBoundingClientRect().width && !el.disabled), {}, { label, scope });
    await handle.asElement().click(); await handle.dispose();
  };
  const waitReady = () => page.waitForFunction(() => ![...document.querySelectorAll('.media-empty')].some(el => el.textContent.includes('Loading')));
  try {
    await page.setViewport({ width: 1440, height: 1000 });
    await page.goto(base + '/admin');
    await page.waitForSelector('input[placeholder="Enter your username or email"]');
    await page.type('input[placeholder="Enter your username or email"]', 'builder-admin');
    await page.type('input[placeholder="Enter password"]', 'Builder-test-password-123!');
    await page.click('button[type="submit"]');
    await click('Media Storage', '.admin-sidebar');
    await page.waitForSelector('.media-storage'); await waitReady();
    await click('New folder', '.media-storage');
    await page.type('.media-folder-form input', 'Browser Campus');
    await click('Create folder', '.media-folder-form');
    await page.waitForFunction(() => [...document.querySelectorAll('.media-child-folders button')].some(el => el.textContent.includes('Browser Campus')));
    await page.evaluate(() => [...document.querySelectorAll('.media-child-folders button')].find(el => el.textContent.includes('Browser Campus')).click());
    await page.waitForFunction(() => document.querySelector('.media-toolbar nav').textContent.includes('Browser Campus'));
    await waitReady();
    await (await page.$('input[aria-label="Upload to Media Storage"]')).uploadFile(uploadPath);
    await page.waitForSelector('.media-card img');
    await page.waitForFunction(() => document.querySelector('.media-notice')?.textContent.includes('1 file added'));
    await click('Details', '.media-card');
    const uniqueUrl = await page.$eval('input[aria-label="Unique media link"]', el => el.value);
    assert.match(uniqueUrl, /\/uploads\/[a-f0-9-]+\.webp$/);
    assert.equal((await fetch(uniqueUrl)).status, 200);
    await page.screenshot({ path: path.join(out, 'storage-desktop.png'), fullPage: true });
    await page.reload(); await click('Media Storage', '.admin-sidebar');
    await page.waitForFunction(() => [...document.querySelectorAll('.media-folders button')].some(el => el.textContent.includes('Browser Campus')));
    await page.evaluate(() => [...document.querySelectorAll('.media-folders button')].find(el => el.textContent.includes('Browser Campus')).click());
    await page.waitForSelector('.media-card img');
    assert.equal(await page.$eval('.media-card img', el => el.src), uniqueUrl);
    await page.setViewport({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(out, 'storage-mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, 'storage fits a phone');
    await page.setViewport({ width: 1440, height: 1000 });
    await click('Homepage', '.admin-sidebar');
    await click('1. Hero Carousel', '.admin-workspace');
    await page.waitForSelector('.media-browse-button');
    await page.click('.media-browse-button');
    await page.waitForSelector('.media-picker-dialog');
    await page.waitForFunction(() => [...document.querySelectorAll('.media-picker-dialog .media-folders button')].some(el => el.textContent.includes('Browser Campus')));
    await page.evaluate(() => [...document.querySelectorAll('.media-picker-dialog .media-folders button')].find(el => el.textContent.includes('Browser Campus')).click());
    await page.waitForSelector('.media-picker-dialog .media-card img');
    await page.click('.media-picker-dialog .media-thumbnail');
    await page.waitForFunction(() => !document.querySelector('.media-picker-dialog'));
    assert.equal(await page.$$eval('input', inputs => inputs.some(el => /^\/uploads\/.+\.webp$/.test(el.value))), true, 'photo field receives stored URL');
    await click('Page Builder', '.admin-sidebar');
    await page.waitForSelector('.pb-manager');
    await click('Create new page', '.pb-app');
    const titleHandle = await page.evaluateHandle(() => [...document.querySelectorAll('.pb-modal label')].find(el => el.querySelector('span')?.textContent === 'Page title').querySelector('input'));
    await titleHandle.asElement().type('Storage selection test');
    await click('Create draft', '.pb-modal');
    await page.waitForSelector('.pb-canvas');
    await click('Image', '.pb-library-item');
    await click('Browse Media Storage', '.pb-inspector');
    await page.waitForSelector('.media-picker-dialog');
    await page.waitForFunction(() => [...document.querySelectorAll('.media-picker-dialog .media-folders button')].some(el => el.textContent.includes('Browser Campus')));
    await page.evaluate(() => [...document.querySelectorAll('.media-picker-dialog .media-folders button')].find(el => el.textContent.includes('Browser Campus')).click());
    await page.waitForSelector('.media-picker-dialog .media-card img');
    await page.screenshot({ path: path.join(out, 'builder-picker.png'), fullPage: true });
    await page.click('.media-picker-dialog .media-thumbnail');
    await page.waitForSelector('.pb-canvas .pb-type-image img');
    assert.equal(await page.$eval('.pb-canvas .pb-type-image img', el => el.src), uniqueUrl);
    const saveResponse = page.waitForResponse(response => /\/api\/page-builder\/[^/]+$/.test(new URL(response.url()).pathname) && response.request().method() === 'PUT' && response.status() === 200);
    await click('Save draft', '.pb-app');
    const saved = await (await saveResponse).json();
    assert(JSON.stringify(saved.document.nodes).includes(new URL(uniqueUrl).pathname), 'saved page references the existing storage URL');
    const persisted = await page.evaluate(async id => (await fetch('/api/page-builder/' + id)).json(), saved.id);
    assert(JSON.stringify(persisted.document.nodes).includes(new URL(uniqueUrl).pathname), 'photo selection persists in the database');
    assert.deepEqual(errors, [], 'no browser runtime crashes');
    console.log('PASS: Media Storage browser: sidebar, folder creation, real upload, unique link, reload persistence, mobile layout, photo-field picker and saved visual page-builder selection.');
  } catch (error) {
    await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true }).catch(() => {});
    throw error;
  } finally { await browser.close(); }
};
